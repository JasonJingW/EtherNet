#!/usr/bin/env python3
"""Project Kconfig entry point. Uses the vendored library, not a pip package.

Requires Python >= 3.9; validated with Python 3.14.6 and Kconfiglib 14.1.0.
Windows terminal mode requires windows-curses == 2.4.2, installed outside the
project with a wheel matching the selected Python version and architecture.
"""

import argparse
import json
import os
from pathlib import Path
import site
import subprocess
import sys
import sysconfig
import tempfile

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parent
MENU = ROOT / "board/config/kconfig"
TOOLS = ROOT / "platform_common" / "kconfig"
TERMINAL_REQUIREMENTS = ("windows-curses==2.4.2; sys_platform == 'win32'",)
sys.path.insert(0, str(TOOLS))
import kconfiglib  # noqa: E402


def load_config(path):
    os.environ["srctree"] = str(ROOT)
    kconf = kconfiglib.Kconfig(str(MENU), warn_to_stderr=False)
    kconf.warn_assign_undef = True
    if not path.is_file():
        raise ValueError(f"Configuration file does not exist: {path}")
    kconf.load_config(str(path))
    return kconf


def validate(kconf):
    values = {symbol.name: symbol.str_value for symbol in kconf.unique_defined_syms}
    errors = list(kconf.warnings)
    for symbol in kconf.unique_defined_syms:
        if symbol.user_value is None:
            continue
        if symbol.type in (kconfiglib.INT, kconfiglib.HEX):
            base = 16 if symbol.type == kconfiglib.HEX else 10
            if int(symbol.str_value, base) != int(symbol.user_value, base):
                errors.append(f"{symbol.name}: requested value is out of range or read-only")
        elif symbol.type == kconfiglib.BOOL:
            if kconfiglib.TRI_TO_STR[symbol.user_value] != symbol.str_value:
                errors.append(f"{symbol.name}: requested state is not available")
    number = lambda name: int(values[name])
    priorities = number("RTOS_MAX_PRIORITIES")
    if values["RTOS_USE_TIMERS"] == "y" and number("RTOS_TIMER_TASK_PRIORITY") >= priorities:
        errors.append("RTOS_TIMER_TASK_PRIORITY must be less than RTOS_MAX_PRIORITIES")
    if values["HEARTBEAT_ENABLED"] == "y":
        if number("HEARTBEAT_TASK_PRIORITY") >= priorities:
            errors.append("HEARTBEAT_TASK_PRIORITY must be less than RTOS_MAX_PRIORITIES")
    name = values["HEARTBEAT_TASK_NAME"]
    if not name or any(ord(char) < 32 or ord(char) == 127 for char in name):
        errors.append("HEARTBEAT_TASK_NAME must be nonempty and contain no control characters")
    if len(name.encode("utf-8")) + 1 > number("RTOS_MAX_TASK_NAME_LEN"):
        errors.append("HEARTBEAT_TASK_NAME does not fit RTOS_MAX_TASK_NAME_LEN")
    # A lower bound only: TCBs, queues, allocation metadata and other objects
    # require additional heap. Final RAM placement still belongs to the linker.
    stack_words = number("RTOS_MINIMAL_STACK_SIZE")
    if values["RTOS_USE_TIMERS"] == "y":
        stack_words += number("RTOS_TIMER_TASK_STACK_DEPTH")
    if values["HEARTBEAT_ENABLED"] == "y":
        stack_words += number("HEARTBEAT_TASK_STACK_DEPTH")
    if number("RTOS_TOTAL_HEAP_SIZE") <= stack_words * 4:
        errors.append("RTOS heap must exceed the combined enabled task stacks, excluding other overhead")
    if errors:
        raise ValueError("Invalid configuration:\n  " + "\n  ".join(dict.fromkeys(errors)))
    return values


def cmake_string(value):
    # Bracket arguments preserve backslashes, dollar signs and semicolons
    # literally, without turning user strings into CMake expressions.
    equals = ""
    while "]" + equals + "]" in value:
        equals += "="
    return "[" + equals + "[" + value + "]" + equals + "]"


def render(kconf, output_dir):
    values = validate(kconf)
    header = ["/* Generated by config.py; edit project.conf through the configuration tool. */",
              "#ifndef PROJECT_AUTOCONF_H", "#define PROJECT_AUTOCONF_H", ""]
    cmake = ["# Generated by config.py. Do not edit."]
    for symbol in kconf.unique_defined_syms:
        value = values[symbol.name]
        if symbol.type == kconfiglib.BOOL:
            c_value = "1" if value == "y" else "0"
            cmake_value = "ON" if value == "y" else "OFF"
        elif symbol.type == kconfiglib.STRING:
            c_value = json.dumps(value, ensure_ascii=False)
            cmake_value = cmake_string(value)
        else:
            numeric = int(value, 16 if symbol.type == kconfiglib.HEX else 10)
            c_value = str(numeric) + "U"
            cmake_value = str(numeric)
        header.append(f"#define CONFIG_{symbol.name} {c_value}")
        cmake.append(f"set(CONFIG_{symbol.name} {cmake_value})")
    header.extend(["", "#endif", ""])
    try:
        relative_root = os.path.relpath(ROOT, output_dir).replace("\\", "/")
        root_expression = '"${CMAKE_CURRENT_LIST_DIR}/' + relative_root + '"'
    except ValueError:  # Different Windows drives cannot have a relative path.
        root_expression = cmake_string(ROOT.as_posix())
    cmake.extend([
        f'get_filename_component(ETHERNET_PROJECT_ROOT {root_expression} ABSOLUTE)',
    ])
    cmake.append("")
    return {
        "project_autoconf.h": "\n".join(header),
        "project_config.cmake": "\n".join(cmake),
    }


def write_if_changed(path, text):
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                     dir=path.parent, delete=False) as stream:
        temporary = Path(stream.name)
        stream.write(text)
    try:
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def save_config(kconf, path):
    with tempfile.TemporaryDirectory(prefix="ethernet-config-") as directory:
        temporary = Path(directory) / "project.conf"
        kconf.write_config(str(temporary), save_old=False)
        write_if_changed(path, temporary.read_text(encoding="utf-8"))


def set_values(kconf, assignments):
    if not assignments:
        raise ValueError("set requires at least one NAME=VALUE assignment")
    for assignment in assignments:
        name, separator, value = assignment.partition("=")
        name = name.removeprefix("CONFIG_")
        symbol = kconf.syms.get(name)
        if not separator or symbol is None or not symbol.nodes:
            raise ValueError(f"Unknown configuration assignment: {assignment}")
        if not any(node.prompt for node in symbol.nodes):
            raise ValueError(f"{name} describes fixed hardware and cannot be edited")
        if symbol.type == kconfiglib.BOOL:
            value = {"1": "y", "0": "n", "true": "y", "false": "n"}.get(value.lower(), value.lower())
        if not symbol.set_value(value):
            raise ValueError(f"Invalid value for {name}: {value}")


def interactive(kconf, command, config):
    script = "guiconfig.py" if command == "gui" else "menuconfig.py"
    if command == "menu":
        try:
            import curses  # noqa: F401
        except ImportError as error:
            raise ValueError("Terminal menu dependency is missing. Run this Python interpreter with config.py setup.") from error
        if not sys.stdin.isatty() or not sys.stdout.isatty():
            raise ValueError("menuconfig needs an interactive terminal. Run python config.py in the VS Code terminal.")
    with tempfile.TemporaryDirectory(prefix="ethernet-config-ui-") as directory:
        working = Path(directory) / "project.conf"
        kconf.write_config(str(working), save_old=False)
        environment = os.environ.copy()
        environment["KCONFIG_CONFIG"] = str(working)
        environment["PYTHONDONTWRITEBYTECODE"] = "1"
        subprocess.run([sys.executable, "-B", str(TOOLS / script), str(MENU)],
                       cwd=ROOT, env=environment, check=True)
        updated = load_config(working)
        validate(updated)
        save_config(updated, config)
    return load_config(config)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("menu", "gui", "generate", "check", "set", "setup"),
                        nargs="?", default="menu")
    parser.add_argument("assignments", nargs="*", metavar="NAME=VALUE")
    parser.add_argument("--config", type=Path, default=ROOT / "board/config/project.conf")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "board/config/generated")
    parser.add_argument("--tools-dir", type=Path, default=os.environ.get("DEV_TOOLS_HOME"),
                        help="External tools directory for setup (default: DEV_TOOLS_HOME)")
    args = parser.parse_args()
    config = args.config.resolve()
    output_dir = args.output_dir.resolve()
    try:
        if args.assignments and args.command != "set":
            raise ValueError("NAME=VALUE arguments are only valid for the set command")
        if args.command == "setup":
            if args.tools_dir is None:
                raise ValueError("Set DEV_TOOLS_HOME or provide --tools-dir for the external tools directory")
            dependencies = args.tools_dir.resolve() / "python" / f"py{sys.version_info.major}{sys.version_info.minor}"
            subprocess.run([sys.executable, "-m", "pip", "install", "--target", str(dependencies),
                            "--upgrade", "--only-binary=:all:", *TERMINAL_REQUIREMENTS],
                           cwd=ROOT, check=True)
            package_directory = Path(site.getusersitepackages() if site.ENABLE_USER_SITE
                                     else sysconfig.get_path("purelib"))
            write_if_changed(package_directory / "project_dev_tools.pth", str(dependencies) + "\n")
            print(f"Terminal dependencies installed: {dependencies}")
            return 0
        kconf = load_config(config)
        if args.command == "set":
            set_values(kconf, args.assignments)
            validate(kconf)
            save_config(kconf, config)
        if args.command in ("gui", "menu"):
            kconf = interactive(kconf, args.command, config)
        outputs = render(kconf, output_dir)
        if args.command == "check":
            stale = [name for name, text in outputs.items()
                     if not (output_dir / name).is_file()
                     or (output_dir / name).read_text(encoding="utf-8") != text]
            if stale:
                raise ValueError("Generated files are missing or stale: " + ", ".join(stale)
                                 + ". Run config.py generate.")
            print("Configuration and generated files are valid and up to date.")
        else:
            for name, text in outputs.items():
                write_if_changed(output_dir / name, text)
            print(f"Configuration generated: {output_dir}")
        return 0
    except (ValueError, OSError, kconfiglib.KconfigError, subprocess.CalledProcessError) as error:
        print(f"Configuration error: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
